import { Permission } from "../../permissions/permissions.catalog.js";
import type { GuideFlow, GuideStepTemplate, GuidePlacement, GuideInteraction } from "./guide.contracts.js";

function step(
  stepId: string,
  order: number,
  titleKey: string,
  instructionKey: string,
  targetId: string,
  placement: GuidePlacement = "auto",
  interaction: GuideInteraction = "click",
  completionEvent: "click" | "route_change" | "value_present" | "manual" = "click",
  routeMatch?: string,
  optional = false,
  fallbackOnMissing: "skip" | "stop" | "wait" = "skip",
  waitMs?: number,
): GuideStepTemplate {
  return {
    stepId,
    order,
    titleKey,
    instructionKey,
    target: { targetId, optional },
    placement,
    interaction,
    completion: { event: completionEvent, routeMatch },
    fallback: { onMissing: fallbackOnMissing, waitMs },
  };
}

