export function createGuideFlowRegistry(): Map<string, GuideFlow> {
  const map = new Map<string, GuideFlow>();
  for (const flow of GUIDE_FLOWS) {
    if (map.has(flow.flowId)) {
      throw new Error(`Duplicate guide flow id: ${flow.flowId}`);
    }
    map.set(flow.flowId, flow);
  }
  return map;
}

export function getGuideFlow(flowId: string): GuideFlow | undefined {
  return createGuideFlowRegistry().get(flowId);
}

export function getAllGuideFlows(): GuideFlow[] {
  return Array.from(createGuideFlowRegistry().values());
}